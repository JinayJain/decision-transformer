import json
import os
import pickle
from functools import lru_cache

import numpy as np
import torch
from torch.utils.data import Dataset


class RolloutDataset(Dataset):
    def __init__(self, data_dir="artifacts/rollouts"):
        """
        Dataset for loading rollout data saved by SaveRolloutsCallback.

        Args:
            data_dir: Directory containing .npz rollout files and metadata.jsonl
        """
        self.data_dir = data_dir
        self.metadata_path = os.path.join(data_dir, "metadata.jsonl")

        # Load metadata to get all file paths
        self.metadata = []
        with open(self.metadata_path, "r") as f:
            for line in f:
                self.metadata.append(json.loads(line))

        # Sort by timestep then episode number
        self.metadata.sort(key=lambda x: (x["timestep"], x["episode"]))

    def __len__(self):
        return len(self.metadata)

    def __getitem__(self, idx):
        meta = self.metadata[idx]
        data = np.load(meta["path"])

        # Convert numpy arrays to torch tensors
        observations = torch.from_numpy(np.array(data["observations"])).float()
        actions = torch.from_numpy(np.array(data["actions"])).float()
        rewards = torch.from_numpy(np.array(data["rewards"])).float()
        dones = torch.from_numpy(np.array(data["dones"])).bool()
        rewards_to_go = torch.from_numpy(np.array(data["rewards_to_go"])).float()

        # Return as dictionary
        return {
            "observations": observations,
            "actions": actions,
            "rewards": rewards,
            "dones": dones,
            "rewards_to_go": rewards_to_go,
            "timestep": meta["timestep"],
            "episode": meta["episode"],
            "total_reward": meta["total_reward"],
            "length": meta["length"],
        }


class ChunkedRolloutDataset(Dataset):
    def __init__(self, data_dir, cache_size=10):
        """
        Dataset for loading chunked rollout data generated by chunk_dataset.py.

        Args:
            data_dir: Directory containing shard_*.npz files and shard_metadata.json.
            cache_size: Max number of shards to keep in the LRU cache.
        """
        self.data_dir = data_dir
        self.metadata_path = os.path.join(data_dir, "shard_metadata.json")

        with open(self.metadata_path, "r") as f:
            self.shard_metadata = json.load(f)

        # Precompute cumulative sample counts for efficient indexing
        self.cumulative_sizes = [0] * (len(self.shard_metadata) + 1)
        self.total_samples = 0
        for i, meta in enumerate(self.shard_metadata):
            self.total_samples += meta["num_samples"]
            self.cumulative_sizes[i + 1] = self.total_samples
            # Store absolute path for loading
            meta["shard_path"] = os.path.join(
                self.data_dir, os.path.basename(meta["shard_path"])
            )

        # Configure the shard loading method with LRU cache
        self._load_shard = lru_cache(maxsize=cache_size)(self._load_shard_from_disk)

    def _load_shard_from_disk(self, shard_index):
        """Loads a specific shard from its npz file."""
        shard_path = self.shard_metadata[shard_index]["shard_path"]
        try:
            # Load the npz file
            with np.load(shard_path) as data:
                # Convert all arrays to a list of samples
                observations = data["observations"]
                actions = data["actions"]
                rewards = data["rewards"]
                dones = data["dones"]
                rewards_to_go = data["rewards_to_go"]
                masks = data["masks"]

                # Create a list with all the samples
                samples = []
                for i in range(len(observations)):
                    samples.append(
                        {
                            "observations": observations[i],
                            "actions": actions[i],
                            "rewards": rewards[i],
                            "dones": dones[i],
                            "rewards_to_go": rewards_to_go[i],
                            "masks": masks[i],
                        }
                    )
                return samples
        except FileNotFoundError:
            print(f"Error: Shard file not found at {shard_path}")
            raise
        except Exception as e:
            print(f"Error loading shard {shard_path}: {e}")
            raise

    def __len__(self):
        return self.total_samples

    def __getitem__(self, idx):
        if idx < 0 or idx >= self.total_samples:
            raise IndexError(
                f"Index {idx} out of range for dataset size {self.total_samples}"
            )

        # Find which shard the index belongs to
        shard_index = np.searchsorted(self.cumulative_sizes, idx, side="right") - 1
        index_within_shard = idx - self.cumulative_sizes[shard_index]

        # Load the shard (potentially from cache)
        shard_data = self._load_shard(shard_index)

        # Get the specific chunk
        chunk = shard_data[index_within_shard]

        # Convert numpy arrays to torch tensors
        return {
            "observations": torch.from_numpy(chunk["observations"]).float(),
            "actions": torch.from_numpy(chunk["actions"]).long(),
            "rewards": torch.from_numpy(chunk["rewards"]).float(),
            "dones": torch.from_numpy(chunk["dones"]).bool(),
            "rewards_to_go": torch.from_numpy(chunk["rewards_to_go"]).float(),
            "masks": torch.from_numpy(chunk["masks"]).bool(),
        }
